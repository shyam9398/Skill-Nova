import React, { useState } from 'react';
import { CheckCircle2, XCircle, Award, AlertCircle, ArrowRight, RotateCcw, Sparkles } from 'lucide-react';
import type { QuizQuestion, QuizAttempt } from '../../types';
import confetti from 'canvas-confetti';
import { dataService } from '../../services/dataService';

interface QuizEngineProps {
  questions: QuizQuestion[];
  topicTitle?: string;
  courseId?: string;
  topicId?: string;
  onFinish?: (attempt: QuizAttempt) => void;
}

export const QuizEngine: React.FC<QuizEngineProps> = ({
  questions,
  topicTitle = 'Topic Assessment',
  onFinish,
}) => {
  const [currentIndex, setCurrentIndex] = useState(0);
  const [selectedOption, setSelectedOption] = useState<number | null>(null);
  const [isAnswerSubmitted, setIsAnswerSubmitted] = useState(false);
  const [score, setScore] = useState(0);
  const [isCompleted, setIsCompleted] = useState(false);
  const [answersHistory, setAnswersHistory] = useState<{ questionId: string; selected: number; isCorrect: boolean }[]>([]);

  if (!questions || questions.length === 0) {
    return (
      <div className="bg-[#101A2D] border border-[#1F2E47] rounded-2xl p-8 text-center text-[#9BAAC2]">
        <Award className="w-10 h-10 text-[#397BFF] mx-auto mb-3 opacity-60" />
        <h4 className="text-base font-semibold text-[#F0F5FF]">No Quiz Questions Available</h4>
        <p className="text-xs mt-1">Quizzes generated by the AI Content Studio will appear here once approved by an instructor.</p>
      </div>
    );
  }

  const currentQ = questions[currentIndex];

  const handleSelect = (idx: number) => {
    if (isAnswerSubmitted) return;
    setSelectedOption(idx);
  };

  const handleSubmitAnswer = () => {
    if (selectedOption === null || isAnswerSubmitted) return;

    const isCorrect = selectedOption === currentQ.correct_index;
    if (isCorrect) {
      setScore(prev => prev + 1);
    }

    setAnswersHistory(prev => [
      ...prev,
      { questionId: currentQ.id, selected: selectedOption, isCorrect },
    ]);

    setIsAnswerSubmitted(true);
  };

  const handleNext = () => {
    if (currentIndex < questions.length - 1) {
      setCurrentIndex(prev => prev + 1);
      setSelectedOption(null);
      setIsAnswerSubmitted(false);
    } else {
      finishQuiz();
    }
  };

  const finishQuiz = () => {
    setIsCompleted(true);
    const finalScore = score + (selectedOption === currentQ.correct_index && !isAnswerSubmitted ? 1 : 0);
    const percentage = Math.round((finalScore / questions.length) * 100);

    if (percentage >= 70) {
      confetti({ particleCount: 100, spread: 70, origin: { y: 0.6 } });
    }

    const currentUser = dataService.getCurrentUser();
    const attempt = dataService.submitQuizAttempt({
      student_id: currentUser ? currentUser.id : 'guest',
      topic_id: currentQ.topic_id,
      score: finalScore,
      total_questions: questions.length,
      percentage,
    });

    if (onFinish) onFinish(attempt);
  };

  const handleRestart = () => {
    setCurrentIndex(0);
    setSelectedOption(null);
    setIsAnswerSubmitted(false);
    setScore(0);
    setIsCompleted(false);
    setAnswersHistory([]);
  };

  if (isCompleted) {
    const percentage = Math.round((score / questions.length) * 100);
    const isMastered = percentage >= 80;

    return (
      <div className="max-w-xl mx-auto bg-[#101A2D] border border-[#1F2E47] rounded-2xl p-8 text-center shadow-2xl">
        <div className="w-16 h-16 rounded-2xl bg-gradient-to-br from-[#397BFF] to-[#101A2D] p-0.5 mx-auto mb-4 shadow-[0_0_20px_rgba(57,123,255,0.4)]">
          <div className="w-full h-full bg-[#080E1C] rounded-[14px] flex items-center justify-center">
            <Award className="w-8 h-8 text-[#77B4FF]" />
          </div>
        </div>

        <h3 className="text-xl font-bold text-[#F0F5FF]">Quiz Assessment Completed!</h3>
        <p className="text-xs text-[#9BAAC2] mt-1">{topicTitle}</p>

        <div className="my-6 p-6 rounded-xl bg-[#15233A] border border-[#1F2E47]">
          <div className="text-4xl font-extrabold text-[#77B4FF] mb-1">
            {percentage}%
          </div>
          <p className="text-xs font-medium text-[#F0F5FF]">
            You scored {score} out of {questions.length} questions correctly.
          </p>
          <div className="mt-3 inline-block px-3 py-1 rounded-full text-xs font-semibold bg-[#397BFF]/20 text-[#77B4FF] border border-[#397BFF]/30">
            {isMastered ? 'Mastery Demonstrated ✨' : 'Review Grounded Materials & Retake'}
          </div>
        </div>

        <div className="flex items-center justify-center gap-3">
          <button
            onClick={handleRestart}
            className="px-4 py-2.5 rounded-xl bg-[#15233A] text-xs font-semibold text-[#F0F5FF] hover:bg-[#1F2E47] border border-[#1F2E47] transition flex items-center gap-1.5"
          >
            <RotateCcw className="w-4 h-4" />
            Retake Quiz
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="max-w-2xl mx-auto space-y-4">
      {/* Header bar */}
      <div className="bg-[#101A2D] border border-[#1F2E47] rounded-xl px-4 py-3 flex items-center justify-between text-xs text-[#9BAAC2]">
        <div className="flex items-center gap-2">
          <Sparkles className="w-4 h-4 text-[#397BFF]" />
          <span className="font-semibold text-[#F0F5FF]">
            Question {currentIndex + 1} of {questions.length}
          </span>
        </div>
        <div className="flex items-center gap-3">
          <span className="text-[#77B4FF] font-medium">Score: {score}</span>
          <div className="w-24 h-2 bg-[#15233A] rounded-full overflow-hidden border border-[#1F2E47]">
            <div
              className="h-full bg-[#397BFF] transition-all duration-300"
              style={{ width: `${((currentIndex + 1) / questions.length) * 100}%` }}
            />
          </div>
        </div>
      </div>

      {/* Question Card */}
      <div className="bg-[#101A2D] border border-[#1F2E47] rounded-2xl p-6 shadow-xl">
        <h3 className="text-base md:text-lg font-bold text-[#F0F5FF] leading-snug mb-5">
          {currentQ.question}
        </h3>

        {/* Options */}
        <div className="space-y-2.5">
          {currentQ.options.map((option, idx) => {
            let optionStyles = 'bg-[#15233A] border-[#1F2E47] text-[#F0F5FF] hover:border-[#397BFF]/50';

            if (selectedOption === idx) {
              optionStyles = 'bg-[#397BFF]/15 border-[#397BFF] text-[#F0F5FF] shadow-[0_0_12px_rgba(57,123,255,0.25)]';
            }

            if (isAnswerSubmitted) {
              if (idx === currentQ.correct_index) {
                optionStyles = 'bg-emerald-500/20 border-emerald-500 text-emerald-200';
              } else if (selectedOption === idx && idx !== currentQ.correct_index) {
                optionStyles = 'bg-rose-500/20 border-rose-500 text-rose-200';
              } else {
                optionStyles = 'bg-[#15233A]/50 border-[#1F2E47] text-[#9BAAC2] opacity-50';
              }
            }

            return (
              <button
                key={idx}
                onClick={() => handleSelect(idx)}
                disabled={isAnswerSubmitted}
                className={`w-full p-3.5 rounded-xl border text-left text-xs md:text-sm font-medium transition-all flex items-center justify-between gap-3 ${optionStyles}`}
              >
                <div className="flex items-center gap-3">
                  <span className="w-6 h-6 rounded-lg bg-[#080E1C] border border-[#1F2E47] text-[11px] font-mono font-bold flex items-center justify-center shrink-0">
                    {String.fromCharCode(65 + idx)}
                  </span>
                  <span>{option}</span>
                </div>

                {isAnswerSubmitted && idx === currentQ.correct_index && (
                  <CheckCircle2 className="w-5 h-5 text-emerald-400 shrink-0" />
                )}
                {isAnswerSubmitted && selectedOption === idx && idx !== currentQ.correct_index && (
                  <XCircle className="w-5 h-5 text-rose-400 shrink-0" />
                )}
              </button>
            );
          })}
        </div>

        {/* Explanation & Grounded Reference Section */}
        {isAnswerSubmitted && (
          <div className="mt-5 p-4 rounded-xl bg-[#15233A] border border-[#1F2E47] text-left animate-in fade-in duration-300">
            <div className="flex items-center gap-2 mb-1.5">
              {selectedOption === currentQ.correct_index ? (
                <div className="text-xs font-bold text-emerald-400 flex items-center gap-1.5">
                  <CheckCircle2 className="w-4 h-4" /> Correct Answer!
                </div>
              ) : (
                <div className="text-xs font-bold text-rose-400 flex items-center gap-1.5">
                  <AlertCircle className="w-4 h-4" /> Incorrect
                </div>
              )}
            </div>

            <p className="text-xs text-[#F0F5FF] leading-relaxed">
              {currentQ.explanation}
            </p>

            {currentQ.source_ref && (
              <div className="mt-3 pt-2 border-t border-[#1F2E47] flex items-center justify-between text-[11px] text-[#9BAAC2]">
                <span className="font-medium text-[#77B4FF]">Source Citation:</span>
                <span className="italic">{currentQ.source_ref}</span>
              </div>
            )}
          </div>
        )}

        {/* Action Button */}
        <div className="mt-6 flex items-center justify-end">
          {!isAnswerSubmitted ? (
            <button
              onClick={handleSubmitAnswer}
              disabled={selectedOption === null}
              className="px-5 py-2.5 rounded-xl bg-[#397BFF] text-xs font-bold text-white hover:bg-[#2868ea] disabled:opacity-40 disabled:cursor-not-allowed shadow-lg shadow-[#397BFF]/30 transition"
            >
              Verify Answer
            </button>
          ) : (
            <button
              onClick={handleNext}
              className="px-5 py-2.5 rounded-xl bg-[#397BFF] text-xs font-bold text-white hover:bg-[#2868ea] shadow-lg shadow-[#397BFF]/30 transition flex items-center gap-2"
            >
              <span>{currentIndex === questions.length - 1 ? 'View Final Results' : 'Next Question'}</span>
              <ArrowRight className="w-4 h-4" />
            </button>
          )}
        </div>
      </div>
    </div>
  );
};
